"""Ударения для синтеза речи: имена и редкие/церковнославянские слова размечаются знаком ударения (U+0301)."""
import re
A = '́'
# слово (как пишется в тексте, без учёта регистра первой буквы) → позиция ударной гласной отмечена «+» после неё
WORDS = '''Эде+мском Эде+ма Ка+ин Авраа+м Исаа+к Иа+ков Изра+иль Изра+иля Изра+илевы коле+нами Ио+сифа Су+щий пе+рвенцев
Сина+й скрижа+лях ро+пщет Иерихо+на Гедео+н Дево+ра Самсо+н свекро+вь Воо+з пра+внук Сау+л Голиа+фа праща+ псалмы+
Па+стырь Соломо+н Иерусали+ме Аха+ве Ваа+лу Или+я Или+ю жрецо+в Карми+л же+ртвенника же+ртвенник ниспа+л всесожже+ние
И+ов Псалты+рь Екклесиа+ст При+тчи Иса+ия Иереми+я Иезеки+иль изъязвле+н му+чим беззако+ния ра+нами исцели+лись
Асси+рия Вавило+н Ио+на чре+ве истука+ну Дании+ла загради+л Есфи+рь Иоа+нна пло+тию Вифлее+ме я+сли Галиле+е самаря+нине
Блаже+нны ни+щие Ла+заря Ла+зарь прослези+лся прома+тывает сжа+лился оса+нна распни+ Иу+ды Голго+фе Соверши+лось заве+са
отва+лен Пятидеся+тницы Дама+ск апо+столом посла+ний пребыва+ют Па+тмос Открове+ние во+пля творю+ Благода+ть Ами+нь
зна+мением заве+та земле+ю ковче+г свине+й Савл Ио+сиф Евре+и'''.split()
MAP = {}
for w in WORDS:
    if '+' not in w: continue
    plain = w.replace('+', '')
    MAP[plain.lower()] = w.replace('+', A)
def stress(text):
    def sub(m):
        w = m.group(0); r = MAP.get(w.lower())
        if not r: return w
        return (r[0].upper() + r[1:]) if w[0].isupper() else r
    return re.sub(r'[А-Яа-яЁё]+', sub, text)
